"""Export atlas cells as separate sprites and instantiate the supplied variable fonts.

The atlas artwork is generated by imagegen; this tool only slices it for Unity.
"""
from pathlib import Path
import shutil
from PIL import Image
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

ROOT = Path(__file__).resolve().parents[2]
THEME = ROOT / 'Assets/UI/PixelTheme'
ATLAS = Path(r'C:/Users/luvpl/.codex/generated_images/01a1307d-cb59-7d11-a32c-8ff376e7d7a1/exec-67bef277-794c-4eff-b6fc-9c30296985e3.png')
SPRITES = {
    'ButtonPrimary': (44, 218, 478, 355),
    'ButtonSecondary': (551, 218, 987, 355),
    'ButtonLight': (1058, 218, 1493, 355),
    'PanelDark': (44, 514, 549, 835),
    'PanelLight': (610, 514, 1112, 835),
    'ButtonIcon': (1208, 566, 1439, 795),
}

def main():
    (THEME / 'Sprites').mkdir(parents=True, exist_ok=True)
    (ROOT / 'Design/PixelTheme').mkdir(parents=True, exist_ok=True)
    shutil.copyfile(ATLAS, ROOT / 'Design/PixelTheme/GeneratedAtlas.png')
    image = Image.open(ATLAS)
    assert image.mode == 'RGBA' and image.size == (1536, 1024)
    for name, rect in SPRITES.items():
        image.crop(rect).save(THEME / 'Sprites' / (name + '.png'))
    for name, axes in [('Tiny5', {'wght': 400, 'wdth': 100, 'BLED': 0, 'JITT': 0, 'ROND': 0}), ('PressStart2P', {}), ('Handjet', {'wght': 500, 'ELGR': 1, 'ELSH': 2})]:
        source = THEME / 'Fonts/Sources' / (name + '-source.ttf')
        font = TTFont(source)
        if axes:
            font = instantiateVariableFont(font, axes, inplace=True)
        assert 'fvar' not in font
        cmap = font.getBestCmap()
        sample = ''.join(chr(c) for c in range(1040, 1104)) + 'Ёё 0123456789'
        missing = sorted(set(sample) - {chr(c) for c in cmap})
        assert not missing, (name, missing)
        if axes:
            font.save(THEME / 'Fonts' / (name + '.ttf'))
        else:
            shutil.copyfile(source, THEME / 'Fonts' / (name + '.ttf'))
        print(name + ': static TTF, Cyrillic verified')
    print('Six separate sprites exported; original atlas retained in Design/PixelTheme.')

if __name__ == '__main__':
    main()
